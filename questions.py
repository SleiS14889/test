# Об'єднаний список усіх питань у порядку проходження боту.
# Кожен елемент: (table_number, category, text)
ALL_QUESTIONS = (
    [(1, cat, text) for cat, text in TABLE1]
    + [(2, cat, text) for cat, text in TABLE2]
)

ANSWER_YES = "yes"
ANSWER_NO = "no"
ANSWER_DK = "dk"  # Не знаю / Не застосовується

ANSWER_LABELS = {
    ANSWER_YES: "Так",
    ANSWER_NO: "Ні",
    ANSWER_DK: "Не знаю / Не застосовується",
}


def compute_score(answers):
    """
    answers: список кортежів (table_number, answer) у тому ж порядку, що ALL_QUESTIONS
    Повертає dict з A, B, C, D, total_score (або None, якщо total_score
    неможливо порахувати через нульовий знаменник).
    """
    a = b = c = d = 0
    for table_number, answer in answers:
        if table_number == 1:
            if answer == ANSWER_YES:
                a += 1
            elif answer == ANSWER_NO:
                b += 1
        else:
            if answer == ANSWER_YES:
                c += 1
            elif answer == ANSWER_NO:
                d += 1

    denom = a + b + c + d
    total_score = (b + c) / denom if denom > 0 else None

    return {"A": a, "B": b, "C": c, "D": d, "total_score": total_score}
